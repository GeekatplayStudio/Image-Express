// Generates the setup-wizard collie mascot sprite sheet and writes it as a
// base64 data URI into src/components/setup/collie-mascot-data.ts (committed,
// so the wizard mascot works without any theme pack installed).
// Usage: node scripts/generate-wizard-mascot.mjs

import { writeFile, mkdir } from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';
import zlib from 'zlib';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

// ---- minimal PNG encoder (self-contained copy; repo tooling) -------------------
const CRC_TABLE = (() => {
    const table = new Uint32Array(256);
    for (let n = 0; n < 256; n += 1) {
        let c = n;
        for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
        table[n] = c >>> 0;
    }
    return table;
})();
const crc32 = (buf) => {
    let c = 0xffffffff;
    for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8);
    return (c ^ 0xffffffff) >>> 0;
};
const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(body));
    return Buffer.concat([len, body, crc]);
};
const encodePng = (width, height, rgba) => {
    const ihdr = Buffer.alloc(13);
    ihdr.writeUInt32BE(width, 0);
    ihdr.writeUInt32BE(height, 4);
    ihdr[8] = 8; ihdr[9] = 6;
    const raw = Buffer.alloc(height * (1 + width * 4));
    for (let y = 0; y < height; y += 1) {
        const rowStart = y * (1 + width * 4);
        raw[rowStart] = 0;
        rgba.copy(raw, rowStart + 1, y * width * 4, (y + 1) * width * 4);
    }
    return Buffer.concat([
        Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
        chunk('IHDR', ihdr),
        chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
        chunk('IEND', Buffer.alloc(0)),
    ]);
};

const PALETTE = {
    K: [38, 38, 44, 255], W: [247, 246, 242, 255], N: [20, 20, 22, 255],
    P: [242, 154, 160, 255],
};
const FRAME_W = 32; const FRAME_H = 22; const FRAMES = 6; // run1 run2 sit1 sit2 wave1 wave2
const data = Buffer.alloc(FRAME_W * FRAMES * FRAME_H * 4);
const px = (f, x, y, c) => {
    if (x < 0 || y < 0 || x >= FRAME_W || y >= FRAME_H) return;
    const [r, g, b, a] = PALETTE[c];
    const i = (y * FRAME_W * FRAMES + f * FRAME_W + x) * 4;
    data[i] = r; data[i + 1] = g; data[i + 2] = b; data[i + 3] = a;
};
const rect = (f, x, y, w, h, c) => {
    for (let yy = y; yy < y + h; yy += 1) for (let xx = x; xx < x + w; xx += 1) px(f, xx, yy, c);
};
const head = (f, hx, hy) => {
    rect(f, hx, hy + 1, 7, 6, 'K');
    rect(f, hx + 1, hy, 5, 1, 'K');
    rect(f, hx, hy - 2, 2, 3, 'K');
    rect(f, hx + 4, hy - 2, 2, 3, 'K');
    rect(f, hx + 5, hy + 3, 5, 4, 'W');
    rect(f, hx + 3, hy + 1, 2, 5, 'W');
    px(f, hx + 5, hy + 2, 'N');
    rect(f, hx + 9, hy + 4, 2, 2, 'N');
    px(f, hx + 7, hy + 7, 'P');
};
const runBody = (f, legPose) => {
    rect(f, 0, 8, 3, 2, 'W');
    rect(f, 2, 9, 4, 3, 'K');
    rect(f, 5, 9, 15, 7, 'K');
    rect(f, 6, 14, 13, 2, 'W');
    rect(f, 17, 8, 4, 8, 'W');
    head(f, 20, 3);
    const leg = (x) => { rect(f, x, 16, 2, 4, 'K'); rect(f, x, 20, 2, 2, 'W'); };
    if (legPose === 0) { leg(7); leg(11); leg(15); leg(19); }
    else { leg(5); leg(13); leg(14); leg(21); }
};
runBody(0, 0);
runBody(1, 1);
const sitBody = (f, pawUp) => {
    rect(f, 8, 12, 10, 8, 'K');
    rect(f, 6, 18, 4, 2, 'W');
    rect(f, 13, 7, 7, 13, 'K');
    rect(f, 15, 10, 4, 10, 'W');
    head(f, 15, 2);
    rect(f, 14, 17, 2, 5, 'K'); rect(f, 14, 20, 2, 2, 'W');
    if (pawUp) { rect(f, 20, 10, 2, 4, 'K'); rect(f, 20, 8, 2, 2, 'W'); }
    else { rect(f, 18, 17, 2, 5, 'K'); rect(f, 18, 20, 2, 2, 'W'); }
};
sitBody(2, false);
sitBody(3, false); px(3, 20, 4, 'K');   // ear flick
sitBody(4, true);                        // wave up
sitBody(5, false); rect(5, 21, 13, 2, 3, 'K'); rect(5, 21, 12, 2, 1, 'W'); // wave mid

const png = encodePng(FRAME_W * FRAMES, FRAME_H, data);
const outDir = path.join(root, 'src', 'components', 'setup');
await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, 'collie-mascot-data.ts'), `// AUTO-GENERATED by scripts/generate-wizard-mascot.mjs — do not edit by hand.
// 32x22 frames, horizontal strip: [run1, run2, sit1, sit2, wave1, wave2]

export const COLLIE_MASCOT_FRAME_WIDTH = ${FRAME_W};
export const COLLIE_MASCOT_FRAME_HEIGHT = ${FRAME_H};
export const COLLIE_MASCOT_FRAMES = ${FRAMES};
export const COLLIE_MASCOT_DATA_URI = 'data:image/png;base64,${png.toString('base64')}';
`);
console.log(`wrote src/components/setup/collie-mascot-data.ts (${png.length} bytes png)`);
